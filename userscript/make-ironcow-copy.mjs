// Writes mwi-fastsim-ironcow.user.js: the main script under the old 铁牛导入 script's address, so
// users who only installed that one keep working after its auto-update. Only the header differs;
// the claim at the top of the script keeps the two from both running when both are installed.
//   node userscript/make-ironcow-copy.mjs   (after every change to mwi-fastsim.user.js)
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const dir = path.dirname(fileURLToPath(import.meta.url))
let s = fs.readFileSync(path.join(dir, "mwi-fastsim.user.js"), "utf8")
const swap = (re, to) => {
  if (!re.test(s)) throw new Error(`header line not found: ${re}`)
  s = s.replace(re, to)
}
swap(/^\/\/ @name {9}.*$/m, "// @name         MWI 战斗工具（铁牛导入旧地址）")
swap(/^\/\/ @name:en {6}.*$/m, "// @name:en      MWI Combat Tools (old ironcow import address)")
swap(/^\/\/ @namespace {4}.*$/m, "// @namespace    mwi-fastsim-ironcow")
swap(/^(\/\/ @description {2}.*)$/m, "$1。和「MWI 战斗工具」是同一个脚本，两个都装时只有一个生效，可以卸载其中一个")
swap(/^(\/\/ @description:en .*)$/m, "$1. Same script as \"MWI Combat Tools\": with both installed only one runs, either can be uninstalled")
swap(/userscript\/mwi-fastsim\.user\.js$/m, "userscript/mwi-fastsim-ironcow.user.js")
swap(/userscript\/mwi-fastsim\.user\.js$/m, "userscript/mwi-fastsim-ironcow.user.js")
s = s.replace("// ==/UserScript==\n", "// ==/UserScript==\n// GENERATED by make-ironcow-copy.mjs from mwi-fastsim.user.js — edit that one.\n")
fs.writeFileSync(path.join(dir, "mwi-fastsim-ironcow.user.js"), s)
console.log("wrote mwi-fastsim-ironcow.user.js")
